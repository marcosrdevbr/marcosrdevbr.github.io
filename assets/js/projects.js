/* ==========================================================
   RESULT TEXT
========================================================== */

function updateProjectsResultText(projectCount, filter) {
  if (!resultText) {
    return;
  }

  const projectWord =
    projectCount === 1
      ? getProjectInterfaceText("project")
      : getProjectInterfaceText("projects");

  if (filter === "all") {
    resultText.textContent = `${getProjectInterfaceText(
      "showingAll",
    )} ${projectCount} ${projectWord}`;

    return;
  }

  const activeButton = document.querySelector(
    `.project-filter-button[data-filter="${filter}"]`,
  );

  const filterName = activeButton ? activeButton.textContent.trim() : filter;

  resultText.textContent = `${getProjectInterfaceText(
    "showing",
  )} ${projectCount} ${filterName} ${projectWord}`;
}

/* ==========================================================
   RENDER ALL PROJECTS
========================================================== */

function renderAllProjects(filter = "all") {
  if (!allProjectsGrid) {
    return;
  }

  const filteredProjects = filterPortfolioProjects(filter);

  allProjectsGrid.innerHTML = filteredProjects
    .map(createAllProjectCard)
    .join("");

  allProjectsGrid.querySelectorAll(".all-project-card").forEach((card) => {
    card.classList.add("visible");
  });

  if (totalProjectsElement) {
    totalProjectsElement.textContent = allPortfolioProjects.length;
  }

  if (emptyState) {
    emptyState.hidden = filteredProjects.length !== 0;
  }

  updateProjectsResultText(filteredProjects.length, filter);
}

/* ==========================================================
   RENDER FEATURED PROJECTS
========================================================== */

function renderFeaturedProjects() {
  if (!featuredProjectsGrid) {
    return;
  }

  const featuredProjects = allPortfolioProjects
    .filter((project) => project.featured)
    .slice(0, 6);

  featuredProjectsGrid.innerHTML = featuredProjects
    .map(createFeaturedProjectCard)
    .join("");
}

/* ==========================================================
   FILTER EVENTS
========================================================== */

function initializeProjectFilters() {
  if (!filtersContainer) {
    return;
  }

  const filterButtons = filtersContainer.querySelectorAll(
    ".project-filter-button",
  );

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const selectedFilter = button.dataset.filter || "all";

      currentFilter = selectedFilter;

      setActiveProjectFilter(button);

      renderAllProjects(selectedFilter);
    });
  });
}

/* ==========================================================
   CLEAR FILTER
========================================================== */

function initializeClearProjectFilter() {
  if (!clearProjectFilterButton) {
    return;
  }

  clearProjectFilterButton.addEventListener("click", () => {
    const allProjectsButton = document.querySelector(
      '.project-filter-button[data-filter="all"]',
    );

    currentFilter = "all";

    if (allProjectsButton) {
      setActiveProjectFilter(allProjectsButton);
    }

    renderAllProjects("all");
  });
}

/* ==========================================================
   UPDATE AFTER LANGUAGE CHANGE
========================================================== */

document.addEventListener("languageChanged", () => {
  renderFeaturedProjects();

  if (allProjectsGrid) {
    const activeFilter = getActiveProjectFilter();

    currentFilter = activeFilter;

    renderAllProjects(activeFilter);
  }
});

/* ==========================================================
   INITIALIZE PROJECTS
========================================================== */

function initializeProjects() {
  if (totalProjectsElement) {
    totalProjectsElement.textContent = allPortfolioProjects.length;
  }

  initializeProjectFilters();

  initializeClearProjectFilter();

  renderFeaturedProjects();

  if (allProjectsGrid) {
    currentFilter = getActiveProjectFilter();

    renderAllProjects(currentFilter);
  }
}

/* ==========================================================
   START
========================================================== */

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initializeProjects);
} else {
  initializeProjects();
}
