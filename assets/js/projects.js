/* ==========================================================
   LANGUAGE HELPERS
========================================================== */

function normalizeProjectLanguage(language) {
  if (!language || typeof language !== "string") {
    return "en";
  }

  const normalizedLanguage = language.toLowerCase();

  if (normalizedLanguage.startsWith("pt")) {
    return "pt-BR";
  }

  if (normalizedLanguage.startsWith("zh")) {
    return "zh-CN";
  }

  return "en";
}

function getCurrentProjectLanguage() {
  const savedLanguage = localStorage.getItem("language");

  if (savedLanguage) {
    return normalizeProjectLanguage(savedLanguage);
  }

  const documentLanguage = document.documentElement.lang;

  if (documentLanguage) {
    return normalizeProjectLanguage(documentLanguage);
  }

  return normalizeProjectLanguage(navigator.language);
}

function getProjectDictionary() {
  const language = getCurrentProjectLanguage();

  return (
    window.projectTranslations?.[language] ||
    window.projectTranslations?.en ||
    null
  );
}

function getProjectTranslation(projectId) {
  const dictionary = getProjectDictionary();

  return (
    dictionary?.projects?.[projectId] ||
    window.projectTranslations?.en?.projects?.[projectId] ||
    null
  );
}

function getProjectInterfaceText(key) {
  const dictionary = getProjectDictionary();

  return (
    dictionary?.interface?.[key] ||
    window.projectTranslations?.en?.interface?.[key] ||
    key
  );
}

function getLocalizedProject(project) {
  const translation = getProjectTranslation(project.id);

  return {
    ...project,

    title: translation?.title || project.id,

    description: translation?.description || "",
  };
}

/* ==========================================================
   HTML SAFETY
========================================================== */

function escapeProjectHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

/* ==========================================================
   TECHNOLOGY TAGS
========================================================== */

function createProjectTechnologyTags(technologies) {
  if (!Array.isArray(technologies)) {
    return "";
  }

  return technologies
    .map(
      (technology) => `
        <span>
          ${escapeProjectHtml(technology)}
        </span>
      `,
    )
    .join("");
}

